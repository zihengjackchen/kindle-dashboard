"""Run on the TrueNAS host: export a small, read-only health snapshot for the NAS collector.

Uses built-in Python and midclt. Does not mount a management socket in Docker.
"""
import argparse
from datetime import datetime, timedelta, timezone
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time


def call(method):
    result = subprocess.run(["midclt", "call", method], capture_output=True, text=True, timeout=15, check=True)
    return json.loads(result.stdout)


def cpu_sample():
    fields = [int(v) for v in Path("/proc/stat").read_text().splitlines()[0].split()[1:9]]
    return sum(fields), fields[3]+fields[4]


def optional(call_api, method, fallback):
    try: return call_api(method)
    except (OSError, ValueError, TypeError, KeyError, subprocess.SubprocessError): return fallback


def job_date(value):
    try:
        if isinstance(value, dict): return datetime.fromtimestamp(value["$date"]/1000, timezone.utc).isoformat()
        if isinstance(value, str): return datetime.fromisoformat(value.replace("Z", "+00:00")).isoformat()
    except (ValueError, KeyError, TypeError, OverflowError): pass
    return None


def backup_summary(task):
    job=task.get("job") or {}
    started, finished=job_date(job.get("time_started")), job_date(job.get("time_finished"))
    schedule=task.get("schedule") or {}
    cron=" ".join(str(schedule.get(k,"*")) for k in ("minute","hour","dom","month","dow"))
    if cron == "0 0 * * sun": cron="Sun 00:00"
    progress=job.get("progress") or {}
    state=str(job.get("state","UNKNOWN"))[:24]
    # Progress description is generated by rclone; include totals only, never paths/errors.
    description=str(progress.get("description", ""))
    import re
    transfer=re.search(r"[\d.]+\s+[KMGT]?i?B\s*/\s*[\d.]+\s+[KMGT]?i?B", description)
    return dict(name=str(task.get("description") or "Backblaze backup")[:80], enabled=bool(task.get("enabled")), state=state,
                last_run=started, last_success=finished if state == "SUCCESS" else None,
                duration_seconds=max(0,int((datetime.fromisoformat(finished)-datetime.fromisoformat(started)).total_seconds())) if started and finished else None,
                percent=max(0,min(100,float(progress["percent"]))) if progress.get("percent") is not None else None,
                schedule=cron[:80], transfer=transfer.group(0) if transfer else "")


def counters():
    result={}
    try:
        result["iowait"]=int(Path('/proc/stat').read_text().splitlines()[0].split()[5])
        rows=[line.split(':',1) for line in Path('/proc/net/dev').read_text().splitlines()[2:] if ':' in line and (Path('/sys/class/net')/line.split(':')[0].strip()/'device').exists()]
        result["rx"]=sum(int(row[1].split()[0]) for row in rows)
        result["tx"]=sum(int(row[1].split()[8]) for row in rows)
        disks=[line.split() for line in Path('/proc/diskstats').read_text().splitlines()]
        # Whole physical devices only; exclude partitions and logical duplicates.
        import re
        disks=[row for row in disks if re.fullmatch(r"sd[a-z]+|nvme\d+n\d+|vd[a-z]+",row[2])]
        result["read"]=sum(int(row[5])*512 for row in disks)
        result["write"]=sum(int(row[9])*512 for row in disks)
    except (OSError, ValueError, IndexError): pass
    return result


def export(pool_name, call_api=call):
    info, pools, alerts = call_api("system.info"), call_api("pool.query"), call_api("alert.list")
    pool = next(p for p in pools if p["name"] == pool_name)
    if not isinstance(alerts, list): raise ValueError("Unexpected alerts response")
    health = pool.get("status", "UNKNOWN")
    if health not in ("ONLINE", "DEGRADED", "FAULTED"): health = "UNKNOWN"
    size, allocated = pool.get("size"), pool.get("allocated")
    used = None
    if size is not None and allocated is not None:
        size, allocated = int(size), int(allocated)
        if size <= 0 or not 0 <= allocated <= size: raise ValueError("Invalid pool capacity")
        used = 100*allocated/size
    mem = {line.split(':')[0]: int(line.split()[1]) for line in Path('/proc/meminfo').read_text().splitlines()}
    before = cpu_sample()
    c_before, t_before = counters(), time.monotonic()
    time.sleep(1)
    after = cpu_sample()
    c_after, elapsed = counters(), max(.001, time.monotonic()-t_before)
    total, idle = after[0]-before[0], after[1]-before[1]
    cpu = max(0, min(100, 100*(1-idle/total))) if total > 0 else None
    now = datetime.now(timezone.utc)
    metrics={"memory_available_gib":mem['MemAvailable']/1048576,"memory_total_gib":mem['MemTotal']/1048576,
             "pool_size_gib":size/2**30 if size else None,"pool_free_gib":(size-allocated)/2**30 if size and allocated is not None else None}
    try:
        for key,value in zip(("load_1m","load_5m","load_15m"),Path('/proc/loadavg').read_text().split()[:3]): metrics[key]=float(value)
    except (OSError, ValueError): pass
    for source,key in (("rx","network_rx_mbps"),("tx","network_tx_mbps"),("read","disk_read_mbps"),("write","disk_write_mbps")):
        if source in c_after and source in c_before: metrics[key]=max(0,c_after[source]-c_before[source])*8/elapsed/1e6
    if total>0 and "iowait" in c_after and "iowait" in c_before: metrics["cpu_iowait_percent"]=max(0,min(100,100*(c_after['iowait']-c_before['iowait'])/total))
    scan=pool.get('scan') or {}
    for source,key in (("state","scrub_state"),("errors","scrub_errors")):
        if source in scan: metrics[key]=scan[source]
    if scan.get('end_time'): metrics['scrub_finished']=job_date(scan['end_time'])
    apps=optional(call_api,'app.query',None)
    if isinstance(apps,list):
        metrics.update(app_count=len(apps), apps_running=sum(a.get('state')=='RUNNING' for a in apps),apps_stopped=sum(a.get('state')=='STOPPED' for a in apps))
    disks=optional(call_api,'disk.query',None)
    if isinstance(disks,list): metrics['disk_count']=len(disks)
    levels={}
    for alert in alerts:
        if not alert.get('dismissed'):
            level=str(alert.get('level','UNKNOWN'))[:16]; levels[level]=levels.get(level,0)+1
    metrics['alert_levels']=', '.join(f'{k}: {v}' for k,v in sorted(levels.items()))[:180] or 'None'
    temps=[]
    for path in Path('/sys/class/hwmon').glob('hwmon*/temp*_input'):
        try:
            if path.parent.joinpath('name').read_text().strip() in ('coretemp','k10temp'): temps.append(int(path.read_text())/1000)
        except (OSError, ValueError): pass
    if temps: metrics['cpu_temperature_c']=max(temps)
    tasks=optional(call_api,'cloudsync.query',[])
    backups=[backup_summary(t) for t in tasks if (t.get('credentials') or {}).get('provider')=='B2' and t.get('direction')=='PUSH'][:8]
    return dict(source="TrueNAS local export", as_of=now.isoformat(), valid_until=(now+timedelta(minutes=30)).isoformat(),
                name=pool_name[:40], version=str(info.get("version", "unknown"))[:40], pool_health=health,
                used_percent=used, cpu_percent=cpu,
                memory_percent=100*(1-mem['MemAvailable']/mem['MemTotal']),
                alerts=sum(not a.get("dismissed", False) for a in alerts), uptime=str(info.get("uptime", "unknown"))[:40], metrics=metrics, backups=backups)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pool", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--report-source", type=Path)
    parser.add_argument("--report-output", type=Path)
    args = parser.parse_args()
    if args.report_source:
        if not args.report_output:
            parser.error('--report-output is required with --report-source')
        from export_stock_report import export_report
        try:
            day = export_report(args.report_source, args.report_output)
            print("Stock report exported: " + day)
        except (OSError, ValueError, KeyError, TypeError):
            print("Stock report export failed; previous report retained")
    try: data = export(args.pool)
    except (OSError, ValueError, TypeError, KeyError, StopIteration, subprocess.SubprocessError) as exc:
        parser.exit(1, f"Export failed ({type(exc).__name__}); previous snapshot retained. Check version and pool name.\n")
    try:
        prior=json.loads(args.output.read_text())
        successes={b['name']:b.get('last_success') for b in prior.get('backups',[])}
        for backup in data['backups']:
            if backup['last_success'] is None: backup['last_success']=successes.get(backup['name'])
    except (OSError, ValueError, KeyError, TypeError): pass
    fd, name = tempfile.mkstemp(prefix="nas-", suffix=".tmp", dir=args.output.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream: json.dump(data, stream)
        os.chmod(name, 0o644)  # contains only selected health fields, no credentials
        os.replace(name, args.output)
    finally:
        if os.path.exists(name): os.unlink(name)
    print("NAS snapshot written")


if __name__ == "__main__": main()
